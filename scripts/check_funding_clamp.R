#!/usr/bin/env Rscript
# Reproducible funding-clamp check for Hyperliquid (JohnGavin/historical#1072).
# Reads perp_funding.parquet (output of scripts/fetch_hyperliquid.R), runs the
# pure functions in R/funding_clamp_check.R, and writes
# audits/funding_clamp_<data max date>.md. That file is the citable home of
# every number; the issue cites it, never the other way round.
#
# Usage: Rscript scripts/check_funding_clamp.R [--in=data/dist/perp_funding.parquet]
#                                              [--audits-dir=audits]
# Exit status: 0 report written | 3 INDETERMINATE: input missing, unreadable,
# or without BTC hourly rows. On 3 nothing is written.

suppressPackageStartupMessages({
  library(dplyr)
  library(arrow)
  library(cli)
})

.fc_script_dir <- function() {
  a <- grep("^--file=", commandArgs(FALSE), value = TRUE)
  cand <- if (length(a) > 0L) dirname(normalizePath(sub("^--file=", "", a[1]))) else character()
  cand <- c(cand, here::here("scripts"))
  cand[file.exists(file.path(dirname(cand), "R", "funding_clamp_check.R"))][1]
}
source(file.path(dirname(.fc_script_dir()), "R", "funding_clamp_check.R"))

.fc_arg <- function(name, default) {
  hit <- grep(paste0("^--", name, "="), commandArgs(TRUE), value = TRUE)
  if (length(hit) == 0L) default else sub(paste0("^--", name, "="), "", hit[1])
}

fc_run <- function(in_path, audits_dir) {
  if (!file.exists(in_path)) {
    cli::cli_alert_danger("Input not found: {in_path}. INDETERMINATE.")
    return(3L)
  }
  df <- tryCatch(
    as.data.frame(arrow::read_parquet(in_path)),
    error = function(e) {
      cli::cli_alert_danger("Cannot read {in_path}: {conditionMessage(e)}. INDETERMINATE.")
      NULL
    }
  )
  if (is.null(df)) return(3L)
  need <- c("dex", "coin", "time", "premium", "interval_hours", "rate_per_hour")
  if (!all(need %in% names(df))) {
    cli::cli_alert_danger("Input lacks column(s): {setdiff(need, names(df))}. INDETERMINATE.")
    return(3L)
  }
  btc <- fc_select(df, dex = FC_BTC_DEX, coin = FC_BTC_COIN)
  if (nrow(btc) == 0L) {
    cli::cli_alert_danger("No BTC hourly rows in {in_path}. INDETERMINATE.")
    return(3L)
  }

  max_time <- max(df$time, na.rm = TRUE)
  max_date <- format(as.Date(as.POSIXct(max_time, tz = "UTC")), "%Y-%m-%d")
  btc_sum <- fc_btc_summary(df)
  band <- fc_band_by_quarter(df)
  xyz <- fc_xyz_summary(df)
  band_post <- band[band$quarter >= paste0(format(FC_BAND_FROM, "%Y"), "Q1"), ]
  band_2023 <- band[grepl("^2023", band$quarter), ]

  out <- c(
    "# Hyperliquid funding clamp check (#1072)",
    "",
    sprintf("- Input file: `%s`", normalizePath(in_path)),
    sprintf("- Rows in file: %d", nrow(df)),
    sprintf("- Max `time`: %s", format(max_time, "%Y-%m-%d %H:%M:%S", tz = "UTC")),
    sprintf("- Generated by: `scripts/check_funding_clamp.R` (functions in `R/funding_clamp_check.R`)"),
    sprintf("- Base rate: %g per hour; band: [%g, %g]; rate rounded to %d dp",
            FC_BASE_RATE, FC_BAND_LO, FC_BAND_HI, FC_RATE_DIGITS),
    sprintf("- Band held fixed from: %s", format(FC_BAND_FROM)),
    "- Quarters and years are UTC calendar periods.",
    "",
    sprintf("## BTC (dex '%s', coin '%s', interval_hours == %g): %d rows",
            FC_BTC_DEX, FC_BTC_COIN, FC_INTERVAL_HOURS, nrow(btc)),
    "",
    "`pct_pinned`: share of rows with rate_per_hour equal to the base rate.",
    "`pct_unexplained`: 100 * (1 - corr(premium, rate)^2).",
    "`pct_ss_pinned`: pinned rows' share of the premium sum of squares about the mean.",
    "",
    fc_md_table(btc_sum),
    "",
    "## BTC: pinned vs in-band, by quarter",
    "",
    "`inband_not_pinned`: premium inside the band but rate not at the base.",
    "`pinned_out_band`: rate at the base but premium outside the band.",
    "",
    fc_md_table(band),
    "",
    sprintf("From %s: in-band-not-pinned total %d, pinned-out-of-band total %d.",
            format(FC_BAND_FROM), sum(band_post$inband_not_pinned), sum(band_post$pinned_out_band)),
    sprintf("2023: in-band-not-pinned total %d.", sum(band_2023$inband_not_pinned)),
    "",
    sprintf("## xyz dex, interval_hours == %g, markets with >= %d rows", FC_INTERVAL_HOURS, FC_MIN_ROWS),
    "",
    "A market's pinned share is the share of rows at its own modal rate.",
    "",
    fc_md_table(xyz),
    ""
  )
  dir.create(audits_dir, showWarnings = FALSE, recursive = TRUE)
  path <- file.path(audits_dir, paste0("funding_clamp_", max_date, ".md"))
  writeLines(out, path)
  cli::cli_alert_success("Wrote {path}")
  0L
}

if (sys.nframe() == 0L) {
  status <- fc_run(
    in_path = .fc_arg("in", "data/dist/perp_funding.parquet"),
    audits_dir = .fc_arg("audits-dir", "audits")
  )
  quit(save = "no", status = status)
}
